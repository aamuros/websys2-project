async (page) => {
    const base='http://127.0.0.1:8766';
    const results=[];
    const pass=name=>results.push({name,status:'PASS'});
    const check=(value,message)=>{if(!value)throw Error(message)};
    const go=async path=>{const r=await page.goto(base+path);check(r.status()===200,path+' HTTP '+r.status())};
    const saved=async()=>page.getByRole('dialog').waitFor({state:'hidden'});
    try {
    await page.getByRole('button',{name:'Log out',exact:true}).click();
    await page.waitForURL(base+'/login');
    await page.getByLabel('Email address',{exact:true}).fill('member@garden.test');
    await page.getByLabel('Password',{exact:true}).fill('Garden123!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.waitForURL(base+'/member/dashboard');
    await page.getByRole('link',{name:'My assignments',exact:true}).first().click();
    await page.waitForURL(base+'/assignments');
    await page.getByRole('button',{name:'Add planting',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Mint',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Add planting',exact:true}).click();
    await saved();
    await page.getByRole('cell',{name:'Mint',exact:true}).waitFor();
    await page.reload();
    await page.getByRole('cell',{name:'Mint',exact:true}).waitFor();
    await page.getByRole('button',{name:'View assignment #5 for plot B-02',exact:true}).click();
    await page.getByRole('dialog').getByRole('cell',{name:'Sunflower',exact:true}).waitFor();
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).first().click();
    pass('Member login, own assignment, planting persistence and assignment history');
    await go('/garden-plots');
    await page.getByRole('searchbox',{name:'Search plots by code or location'}).fill('A-04');
    const plot=page.getByRole('article').filter({hasText:'A-04'});
    await plot.getByRole('button',{name:'Request plot',exact:true}).click();
    await page.getByRole('button',{name:'Submit request',exact:true}).click();
    await page.getByText('Tell us briefly how you plan to use the plot.',{exact:true}).waitFor();
    await page.getByLabel('How will you use this plot?',{exact:true}).fill('Submission test: herbs and vegetables for the community.');
    await page.getByRole('button',{name:'Submit request',exact:true}).click();
    await saved();
    await plot.getByRole('button',{name:'Requested',exact:true}).waitFor();
    await go('/plot-requests');
    const request=page.getByRole('button',{name:/View request #\d+ for Plot A-04/i});
    await request.click();
    await page.getByRole('dialog').getByText('Submission test: herbs and vegetables for the community.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Cancel request',exact:true}).click();
    await page.getByRole('button',{name:'Cancel request',exact:true}).click();
    await saved();
    await page.getByText('Cancelled',{exact:true}).first().waitFor();
    pass('Plot search, request validation, submission, own request details and cancellation');
    await go('/community-updates');
    await page.getByRole('button',{name:'Read update: Submission admin announcement',exact:true}).click();
    await page.getByRole('dialog').getByText('Submission browser verification announcement.',{exact:true}).waitFor();
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).first().click();
    check(await page.getByRole('button',{name:'New update',exact:true}).count()===0,'Member can manage announcements');
    for(const path of ['/admin/dashboard','/staff/dashboard','/reports','/members','/crops'])check((await page.request.get(base+path)).status()===403,'Member boundary failed '+path);
    pass('Member sees published admin announcement and role boundaries hold');
    await page.setViewportSize({width:390,height:844});
    await go('/assignments');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Member mobile overflow');
    await page.getByRole('button',{name:'Open navigation',exact:true}).click();
    await page.getByRole('dialog').getByRole('link',{name:'My plot requests',exact:true}).click();
    await page.waitForURL(base+'/plot-requests');
    await saved();
    await page.setViewportSize({width:1280,height:800});
    pass('Member mobile assignment layout and navigation');
    return {results};
    }catch(e){return {results,failure:e.message}}
}
